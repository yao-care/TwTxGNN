#!/usr/bin/env python3
"""關閉已反映在頁面上的「TFDA 許可證變更」issue（2026-11-24，用戶決定 TFDA 重產接進每週排程）。

check-new-evidence 每天比對 TFDA 資料集、有變更就開 label=tfda 的 issue；每週排程重產程式化許可證表後，
逐筆確認 issue 列的變更都在頁面上，全部確認得到才留言關閉，有一筆確認不了就留著給人看：
  狀態→註銷：該字號出現的每頁都在「已註銷」區；狀態→有效（有效日期 X）：每列都有 X（複方表沒有有效日期欄，算確認）；
  新增許可證：字號出現在頁面上；製造廠變更：頁面不顯示（表格欄位是申請商），不影響判定；
  字號不在任何頁：依主成分比對不屬於本站任何藥（例：名稱子字串誤比對），列在留言裡，不算確認失敗。
用法（repo 根目錄，需要 GH_TOKEN 與 gh）：python3 scripts/close_reflected_tfda_issues.py --repo owner/repo --commit <sha> [--dry-run]
"""
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def gh(*args, data=None):
    r = subprocess.run(["gh", "api", *args], capture_output=True, text=True, input=data)
    if r.returncode:
        raise RuntimeError(r.stderr.strip()[-300:])
    return json.loads(r.stdout) if r.stdout.strip() else None


def windows(pages, lid):
    out = []
    for name, s in pages.items():
        for m in re.finditer(re.escape(lid), s):
            w = s[m.start():m.start() + 900]
            w = w.split("</tr>")[0] if "<td" in w[:200] else w.split("\n")[0]
            sec = max(s[:m.start()].rfind("<summary><strong>"), s[:m.start()].rfind("**有效"))
            out.append((name, s[sec:sec + 40] if sec >= 0 else "", w))
    return out


def check(body, pages):
    """回傳 (全部確認, 說明清單)"""
    notes, ok = [], True
    blk = body.split("### 詳細資訊")[-1].split("### 建議")[0]
    items = re.split(r"\n- \*\*", blk)[1:]
    if not items:
        return False, ["issue 內文沒有可解析的許可證變更"]
    for it in items:
        lid = it.split("**")[0].strip()
        wins = windows(pages, lid)
        changes = re.findall(r"  - ([^:]+): ([^\n]*) → ([^\n]*)", it)
        if not wins:
            notes.append(f"{lid}：依主成分比對不屬於本站任何藥物頁，不需改頁")
            continue
        if not changes:  # 新增許可證
            notes.append(f"{lid}：已列在 {', '.join(sorted({n for n, _, _ in wins}))}")
            continue
        for field, _old, new in changes:
            if field == "製造廠":
                notes.append(f"{lid} 製造廠變更：頁面不顯示（表格欄位是申請商）")
                continue
            if field == "狀態":
                d = re.search(r"(\d{4}/\d{2}/\d{2})", new)
                if "註銷" in new:
                    good = all("註銷" in lab for _, lab, _ in wins)
                else:
                    good = bool(d) and all(d.group(1) in w or "複方" in lab for _, lab, w in wins)
            else:
                good = all(new.strip()[:15] in w for _, _, w in wins)
            notes.append(f"{lid} {field} → {new.strip()[:40]}：{'已反映' if good else '頁面上確認不到'}")
            ok &= good
    return ok, notes


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--commit", required=True)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    pages = {p.stem: p.read_text(encoding="utf-8") for p in (ROOT / "docs/_drugs").glob("*.md")}
    issues = gh(f"repos/{a.repo}/issues?state=open&labels=tfda&per_page=100") or []
    closed = kept = 0
    for i in issues:
        if "pull_request" in i:
            continue
        good, notes = check(i.get("body") or "", pages)
        print(f"#{i['number']} {'close' if good else 'keep'}：" + "；".join(notes))
        if a.dry_run:
            continue
        if good:
            msg = (f"每週排程已依 TFDA 資料集 36 重產程式化許可證表（{a.commit}），本 issue 的變更已反映在頁面上：\n- "
                   + "\n- ".join(notes) + FOOTER)
            gh(f"repos/{a.repo}/issues/{i['number']}/comments", "-f", f"body={msg}")
            gh("-X", "PATCH", f"repos/{a.repo}/issues/{i['number']}", "-f", "state=closed", "-f", "state_reason=completed")
            closed += 1
        else:
            kept += 1
    print(f"關閉 {closed} 個、留下 {kept} 個")


if __name__ == "__main__":
    main()
